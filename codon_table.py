def display_codon_table():
    """Print all codons and their amino-acid symbols."""
    print("\nSTANDARD GENETIC CODE")
    print("-" * 28)

    for codon, amino_acid in sorted(CODON_TABLE.items()):
        label = "STOP" if amino_acid == "*" else amino_acid
        print(f"{codon} : {label}")

    print(f"\nTotal codons: {len(CODON_TABLE)}")


